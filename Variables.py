#prijzen
appel = 1
banaan = 2
sinaasappel = 3

#verkochte aantallen
aantal_appel = 8
aantal_banaan = 5
aantal_sinaasappel = 7

#omzet berekenen
totale_omzet = (appel * aantal_appel) + (banaan * aantal_banaan) + (sinaasappel * aantal_sinaasappel)

#producten tonen
print("appel:", appel, "euro -", aantal_appel, "verkocht")
print("Banaan:", banaan, "euro -", aantal_banaan, "verkocht")
print("sinaasappel:", sinaasappel, "euro -", aantal_sinaasappel, "verkocht")

#totale omzet tonen
print("Totale omzet:", totale_omzet, "euro")